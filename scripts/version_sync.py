#!/usr/bin/env python3
"""Keep every version surface in step with the repository's VERSION file.

``VERSION`` is the only place the current release number is edited by hand.
Everything a machine reads is derived from it:

    android/version.properties          version + derived versionCode
    macos/app/package.json              Electron/electron-builder version
    macos/app/package-lock.json         the lockfile's root version

Everything that has to stay readable prose is *checked*, never rewritten:
the README release table, the two app READMEs, docs/UPDATES.md, the update
notice, the release notes file and both build workflows.  When one of them
disagrees the check names the file and the expected value, and CI fails.

    python scripts/version_sync.py            # check (CI uses this)
    python scripts/version_sync.py --write    # update the generated surfaces
    python scripts/version_sync.py --current  # print the current version

The policy for the version itself - and for the Android versionCode - stays in
``scripts/release_version.py``; this script only propagates and verifies it.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import release_version  # noqa: E402

PROPERTIES_PATH = ROOT / "android" / "version.properties"
PACKAGE_PATH = ROOT / "macos" / "app" / "package.json"
LOCK_PATH = ROOT / "macos" / "app" / "package-lock.json"
GRADLE_PATH = ROOT / "android" / "app" / "build.gradle.kts"

PROPERTIES_HEADER = (
    "# Generated by scripts/version_sync.py from the repository VERSION file.\n"
    "# Do not edit: run `python scripts/version_sync.py --write` instead.\n"
)


def expected_properties(version: str, code: int) -> str:
    return f"{PROPERTIES_HEADER}version={version}\nversionCode={code}\n"


def read_properties(path: Path = PROPERTIES_PATH) -> dict[str, str]:
    values: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return values
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def write_generated(version: str, code: int) -> list[str]:
    """Write the machine-read surfaces; return the paths that changed."""
    changed: list[str] = []

    text = expected_properties(version, code)
    if not PROPERTIES_PATH.is_file() or PROPERTIES_PATH.read_text(encoding="utf-8") != text:
        PROPERTIES_PATH.parent.mkdir(parents=True, exist_ok=True)
        PROPERTIES_PATH.write_text(text, encoding="utf-8")
        changed.append(str(PROPERTIES_PATH.relative_to(ROOT)))

    for path in (PACKAGE_PATH, LOCK_PATH):
        if not path.is_file():
            continue
        document = json.loads(path.read_text(encoding="utf-8"))
        if path == PACKAGE_PATH:
            if document.get("version") == version:
                continue
            document["version"] = version
        else:
            changed_here = False
            if document.get("version") != version:
                document["version"] = version
                changed_here = True
            packages = document.get("packages")
            if isinstance(packages, dict) and isinstance(packages.get(""), dict):
                if packages[""]["version"] != version:
                    packages[""]["version"] = version
                    changed_here = True
            if not changed_here:
                continue
        path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
        changed.append(str(path.relative_to(ROOT)))
    return changed


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _require_text(problems: list[str], path: Path, needles: list[str], label: str) -> None:
    text = _read(path)
    if not text:
        problems.append(f"{path.relative_to(ROOT)}: missing (needed for {label})")
        return
    for needle in needles:
        if needle not in text:
            problems.append(
                f"{path.relative_to(ROOT)}: expected {needle!r} ({label}); "
                f"VERSION is {release_version.current_version()}"
            )


def check() -> list[str]:
    """Every surface that must agree with VERSION.  An empty list means clean."""
    problems: list[str] = []
    try:
        version = release_version.current_version()
    except ValueError as error:
        return [str(error)]
    code = release_version.android_version_code(version)

    # --- generated by --write -------------------------------------------
    properties = read_properties()
    if properties.get("version") != version:
        problems.append(
            "android/version.properties: version is %r, VERSION is %r - run "
            "`python scripts/version_sync.py --write`" % (properties.get("version"), version)
        )
    if properties.get("versionCode") != str(code):
        problems.append(
            "android/version.properties: versionCode is %r, expected %r - run "
            "`python scripts/version_sync.py --write`" % (properties.get("versionCode"), code)
        )

    if PACKAGE_PATH.is_file():
        package = json.loads(PACKAGE_PATH.read_text(encoding="utf-8"))
        if package.get("version") != version:
            problems.append(
                "macos/app/package.json: version is %r, VERSION is %r - run "
                "`python scripts/version_sync.py --write`" % (package.get("version"), version)
            )
    else:
        problems.append("macos/app/package.json: missing")

    if LOCK_PATH.is_file():
        lock = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
        if lock.get("version") != version:
            problems.append(
                "macos/app/package-lock.json: version is %r, VERSION is %r - run "
                "`python scripts/version_sync.py --write`" % (lock.get("version"), version)
            )
        root_lock = (lock.get("packages") or {}).get("") or {}
        if root_lock.get("version") != version:
            problems.append(
                "macos/app/package-lock.json: packages[\"\"].version is %r, VERSION is %r - run "
                "`python scripts/version_sync.py --write`"
                % (root_lock.get("version"), version)
            )
    else:
        problems.append("macos/app/package-lock.json: missing")

    # --- read by the builds ---------------------------------------------
    gradle = _read(GRADLE_PATH)
    for needle in ('version.properties', 'getProperty("version"', 'getProperty("versionCode"'):
        if needle not in gradle:
            problems.append(
                "android/app/build.gradle.kts: does not read the generated "
                "version properties (%r missing)" % needle
            )
    if re.search(r'orElse\("\d+\.\d+\.\d+', gradle):
        problems.append(
            "android/app/build.gradle.kts: hardcodes a version fallback; read "
            "android/version.properties instead"
        )

    bundle = _read(ROOT / "android" / "tools" / "build_bundle.py")
    if "release_version.current_version()" not in bundle:
        problems.append(
            "android/tools/build_bundle.py: DEFAULT_VERSION must come from "
            "scripts/release_version.current_version(), not a literal"
        )
    if re.search(r'DEFAULT_VERSION\s*=\s*"\d+\.\d+\.\d+', bundle):
        problems.append("android/tools/build_bundle.py: hardcodes DEFAULT_VERSION")

    site = _read(ROOT / "scripts" / "build_site_data.py")
    if "current_version()" not in site:
        problems.append(
            "scripts/build_site_data.py: the CHANNELS fallback must use "
            "release_version.current_version()"
        )

    for name in ("android-build.yml", "macos-build.yml"):
        workflow = _read(ROOT / ".github" / "workflows" / name)
        if "--current" not in workflow:
            problems.append(
                f".github/workflows/{name}: must resolve the default version with "
                "`scripts/release_version.py --current`"
            )
        if re.search(r'default:\s*"\d+\.\d+\.\d+', workflow) or re.search(
            r"\|\|\s*'\d+\.\d+\.\d+'", workflow
        ):
            problems.append(f".github/workflows/{name}: hardcodes a version fallback")

    # --- prose that has to be updated with the release -------------------
    _require_text(
        problems, ROOT / "README.md",
        [f"**Stable release** | **{version}**", f"versionCode {code}"],
        "README release table",
    )
    _require_text(
        problems, ROOT / "android" / "README.md",
        [f"**{version}**", f"`{code}`"],
        "Android README build target",
    )
    _require_text(
        problems, ROOT / "macos" / "README.md",
        [f"**{version} stable build", f"`v{version}`"],
        "macOS README build target",
    )
    _require_text(
        problems, ROOT / "docs" / "UPDATES.md",
        [f"current stable release is **{version}**"],
        "update policy",
    )
    _require_text(
        problems, ROOT / f"release-notes-{version}.md",
        [f"PremiumTV {version}"],
        "release notes for the current version",
    )

    notice_path = ROOT / "app-update-notice.json"
    try:
        notice = json.loads(notice_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        problems.append(f"app-update-notice.json: cannot read ({error})")
    else:
        rules = {rule.get("id"): rule for rule in notice.get("rules") or []}
        stable = rules.get("update-below-newest")
        if not stable:
            problems.append("app-update-notice.json: missing the update-below-newest rule")
        else:
            highest = stable.get("max_version")
            if not highest or highest == version or (
                release_version.compare_versions(highest, version) or 0
            ) >= 0:
                problems.append(
                    "app-update-notice.json: update-below-newest.max_version must be "
                    f"below {version}, got {highest!r}"
                )
            else:
                # A patch bump must also nudge the build it replaces: with
                # VERSION 1.1.3, a max_version of 1.1.1 would silently skip
                # 1.1.2.  A minor/major bump has no single predecessor, so the
                # "below current" rule above is all that can be checked.
                parts = release_version.parse_version(version) or ()
                if len(parts) == 3 and parts[2] > 0:
                    expected = f"{parts[0]}.{parts[1]}.{parts[2] - 1}"
                    if (release_version.compare_versions(highest, expected) or 0) < 0:
                        problems.append(
                            "app-update-notice.json: update-below-newest.max_version is "
                            f"{highest!r}, which skips {expected}; it must cover every "
                            f"build below {version}"
                        )
            if f"{version}" not in str(stable.get("surprise") or ""):
                problems.append(
                    "app-update-notice.json: update-below-newest.surprise should name "
                    f"{version} so the popup describes the current release"
                )

    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify every surface (default)")
    parser.add_argument("--write", action="store_true", help="update the generated surfaces")
    parser.add_argument("--current", action="store_true", help="print the current version")
    args = parser.parse_args(argv)

    try:
        version = release_version.current_version()
    except ValueError as error:
        print(f"[version] {error}", file=sys.stderr)
        return 1
    code = release_version.android_version_code(version)

    if args.current:
        print(version)
        return 0

    if args.write:
        changed = write_generated(version, code)
        if changed:
            for path in changed:
                print(f"[version] wrote {path}")
        else:
            print(f"[version] generated surfaces already at {version}")
        problems = check()
        if problems:
            print(
                f"[version] {version} written, but these still need a human edit:",
                file=sys.stderr,
            )
            for problem in problems:
                print(f"[version]   - {problem}", file=sys.stderr)
            return 1
        return 0

    problems = check()
    if problems:
        for problem in problems:
            print(f"[version] DRIFT: {problem}", file=sys.stderr)
        return 1
    print(f"[version] OK {version} ({code}) across every surface")
    return 0


if __name__ == "__main__":
    sys.exit(main())
