  function toast(message) {
    var el = $("toast");
    el.textContent = message;
    el.hidden = false;
    clearTimeout(toastTimer);
    toastTimer = setTimeout(function () { el.hidden = true; }, 2600);
  }
  function copyText(text, okMessage) {
    function fallback() {
      var ta = document.createElement("textarea");
      ta.value = text;
      ta.style.position = "fixed";
      ta.style.opacity = "0";
      document.body.appendChild(ta);
      ta.select();
      try { document.execCommand("copy"); } catch (e) { /* ignore */ }
      document.body.removeChild(ta);
      toast(okMessage || "Copied");
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(function () {
        toast(okMessage || "Copied");
      }, fallback);
    } else {
      fallback();
    }
  }

  /* Fetch a repository file as text, trying every public mirror. */
  var MIRRORS = [
    function (path) { return "https://raw.githubusercontent.com/" + D.repo.owner + "/" + D.repo.name + "/" + D.repo.branch + "/" + path; },
    function (path) { return "https://cdn.jsdelivr.net/gh/" + D.repo.owner + "/" + D.repo.name + "@" + D.repo.branch + "/" + path; },
    function (path) { return "https://github.com/" + D.repo.owner + "/" + D.repo.name + "/raw/" + D.repo.branch + "/" + path; }
  ];
  function fetchRepoText(path) {
    var i = 0;
    function next() {
      if (i >= MIRRORS.length) return Promise.reject(new Error("all mirrors failed"));
      var url = MIRRORS[i++](path);
      return fetch(url, { cache: "no-store" }).then(function (r) {
        if (!r.ok) throw new Error("HTTP " + r.status);
        return r.text();
      }).catch(next);
    }
    return next();
  }

