  function showQr() {
    var url = $("playlist-url").textContent;
    var box = $("qr-box");
    if (!box.hidden) { box.hidden = true; return; }
    try {
      var qr = window.qrcode(0, "M");
      qr.addData(url);
      qr.make();
      var canvas = $("qr-canvas");
      var ctx = canvas.getContext("2d");
      if (qr.renderTo2dContext) {
        ctx.fillStyle = "#fff";
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        qr.renderTo2dContext(ctx, 6);
      } else {
        var img = new Image();
        img.onload = function () {
          ctx.fillStyle = "#fff";
          ctx.fillRect(0, 0, canvas.width, canvas.height);
          ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
        };
        img.src = qr.createDataURL(6, 8);
      }
      box.hidden = false;
    } catch (e) {
      toast("QR rendering failed in this browser");
    }
  }

