  function parsePlaylist(text) {
    var lines = text.split(/\r?\n/);
    var entries = [];
    var pending = null;
    var guides = [];
    for (var i = 0; i < lines.length; i++) {
      var line = lines[i].trim();
      if (!line) continue;
      if (line.indexOf("#EXTM3U") === 0) {
        var m = line.match(/x-tvg-url="([^"]*)"/i) || line.match(/x-tvg-url=([^ ]+)/i);
        if (m) guides.push(m[1]);
        continue;
      }
      if (line.indexOf("#EXTINF") === 0) { pending = line; continue; }
      if (line[0] === "#") continue;
      if (pending) { entries.push({ info: pending, url: line }); pending = null; }
    }
    return { entries: entries, guides: guides };
  }

  function buildBundle() {
    var slugs = Object.keys(bundleSelected);
    var status = $("bundle-status");
    if (!slugs.length) {
      status.className = "bundle-status err";
      status.textContent = "Pick at least one country first.";
      return;
    }
    status.className = "bundle-status";
    status.textContent = "Fetching " + slugs.length + " playlist(s)…";
    var results = [];
    var chain = Promise.resolve();
    slugs.forEach(function (slug) {
      chain = chain.then(function () {
        var c = bySlug[slug];
        return fetchRepoText("playlists/countries/" + slug + ".m3u").then(function (text) {
          results.push({ country: c, data: parsePlaylist(text) });
          status.textContent = "Fetched " + results.length + " / " + slugs.length + "…";
        }).catch(function () {
          results.push({ country: c, data: { entries: [], guides: [] }, failed: true });
        });
      });
    });
    chain.then(function () {
      var seen = {};
      var entries = [];
      var guides = [];
      var total = 0;
      var failed = [];
      results.forEach(function (r) {
        if (r.failed) { failed.push(r.country.name); return; }
        r.data.guides.forEach(function (g) {
          if (guides.indexOf(g) < 0) guides.push(g);
        });
        r.data.entries.forEach(function (e) {
          total++;
          if (seen[e.url]) return;
          seen[e.url] = true;
          entries.push(e);
        });
      });
      if (!entries.length) {
        status.className = "bundle-status err";
        status.textContent = "Could not fetch any playlist. Check your connection and try again.";
        return;
      }
      var header = "#EXTM3U";
      if (guides.length) header += " x-tvg-url=\"" + guides.slice(0, 2).join(",") + "\"";
      var body = entries.map(function (e) { return e.info + "\n" + e.url; }).join("\n");
      var names = slugs.map(function (s) { return bySlug[s] ? bySlug[s].slug : s; });
      saveText(header + "\n# PremiumTV bundle (" + names.join(", ") + ")\n" + body + "\n",
               "PremiumTV-bundle-" + names.slice(0, 4).join("-") +
               (names.length > 4 ? "-etc" : "") + ".m3u");
      status.className = "bundle-status ok";
      status.textContent = "Downloaded " + entries.length + " unique channels from " +
        (slugs.length - failed.length) + " playlist(s)" +
        (failed.length ? " — failed: " + failed.join(", ") : "") + ".";
    });
  }

