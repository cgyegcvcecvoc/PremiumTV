  /* country detection (browser-side; no data leaves the page)          */
  /* ------------------------------------------------------------------ */
  var detected = null;

  function matchCountry(iso2, name) {
    if (iso2) {
      for (var i = 0; i < countries.length; i++) {
        if (countries[i].iso2 && countries[i].iso2.toUpperCase() === iso2.toUpperCase()) {
          return countries[i];
        }
      }
    }
    if (name) {
      var n = name.toLowerCase();
      for (var j = 0; j < countries.length; j++) {
        if (countries[j].name.toLowerCase() === n) return countries[j];
        if (countries[j].name.toLowerCase().indexOf(n) >= 0) return countries[j];
      }
    }
    return null;
  }

  function applyDetected(country, source) {
    detected = country;
    var flag = $("detect-flag"), title = $("detect-title"), sub = $("detect-sub");
    if (country) {
      flag.textContent = flagOf(country);
      title.textContent = country.name;
      sub.textContent = Number(country.count).toLocaleString() + " confirmed-working channels · " +
        (source || "detected");
      $("hero-get").textContent = "Get " + country.name + "’s playlist";
      $("hero-get").onclick = function () {
        selectCountry(country.slug, true);
        return false;
      };
      $("use-detected").hidden = false;
    } else {
      flag.textContent = "🌍";
      title.textContent = "Choose your country";
      sub.textContent = "We couldn’t detect it — pick one below.";
    }
  }

  function detectCountry() {
    var attempts = [
      { url: "https://ipwho.is/", parse: function (j) { return matchCountry(j.country_code2 || j.country_code, j.country); } },
      { url: "https://ipapi.co/json/", parse: function (j) { return matchCountry(j.country_code, j.country_name); } },
      { url: "https://country.is/", parse: function (j) { return matchCountry(j.country, null); } }
    ];
    var i = 0;
    var settled = false;
    function tryNext() {
      if (settled) return;
      if (i >= attempts.length) { settled = true; applyDetected(null); return; }
      var attempt = attempts[i++];
      var timer = setTimeout(tryNext, 4000);
      fetch(attempt.url, { cache: "no-store" })
        .then(function (r) { return r.ok ? r.json() : Promise.reject(); })
        .then(function (j) {
          clearTimeout(timer);
          if (settled) return;
          var c = attempt.parse(j);
          if (c) {
            settled = true;
            applyDetected(c, "detected via " + attempt.url.split("/")[2]);
          } else {
            tryNext();
          }
        })
        .catch(function () { clearTimeout(timer); tryNext(); });
    }
    tryNext();
  }

