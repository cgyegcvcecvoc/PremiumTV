  function downloadPlaylist(url, filename) {
    fetchRepoText(repoPathOf(url)).then(function (text) {
      saveText(text, filename);
    }).catch(function () {
      // Mirrors blocked? Fall back to opening the raw file.
      window.open(url, "_blank", "noopener");
      toast("Opened the raw file — save it from your browser");
    });
  }

  function saveText(text, filename) {
    var blob = new Blob([text], { type: "audio/x-mpegurl" });
    var a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      URL.revokeObjectURL(a.href);
      document.body.removeChild(a);
    }, 400);
  }

